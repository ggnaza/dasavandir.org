#!/usr/bin/env node
/**
 * Generate the idempotent seed migration for Gnahatum diagnostic answer keys.
 *
 * Input:  one JSON file per test under the directory given as argv[2],
 *         shaped { subject, grade, doc, notes, key: AnswerKeyItem[] }.
 * Output: SQL on stdout.
 *
 * Every key is validated before it is emitted — 15 questions, points matching
 * the fixed distribution, total exactly 15. A malformed key must fail here
 * rather than reach the database, because a wrong answer key silently
 * mis-grades real students.
 */

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const POINT_DISTRIBUTION = {
  1: 0.5, 2: 0.5, 3: 1, 4: 1, 5: 1, 6: 1, 7: 1,
  8: 0.5, 9: 0.5, 10: 1, 11: 1, 12: 1, 13: 1.5, 14: 1.5,
  15: 2,
};

const VALID_TYPES = new Set([
  "multiple_choice", "fill_blank", "matching", "short_answer",
  "computation", "essay", "table", "diagram", "true_false",
]);

// Existing rows use '2025'; `tests` is UNIQUE (subject_id, grade, test_type,
// year), so a different string here would create a duplicate test rather than
// update the intended one.
const YEAR = "2025";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: build-gnahatum-keys-sql.mjs <keys-dir>");
  process.exit(1);
}

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const rows = [];
const problems = [];

for (const file of files) {
  const data = JSON.parse(readFileSync(join(dir, file), "utf8"));
  const { subject, grade, doc, notes, key } = data;

  if (!subject || !grade || !Array.isArray(key)) {
    problems.push(`${file}: missing subject, grade or key`);
    continue;
  }
  if (key.length !== 15) {
    problems.push(`${file}: expected 15 questions, found ${key.length}`);
    continue;
  }

  let total = 0;
  for (const item of key) {
    const expected = POINT_DISTRIBUTION[item.number];
    if (expected === undefined) {
      problems.push(`${file}: Q${item.number} is not a valid question number`);
    } else if (Math.abs(item.points - expected) > 0.001) {
      problems.push(`${file}: Q${item.number} has ${item.points} pts, expected ${expected}`);
    }
    if (!VALID_TYPES.has(item.type)) {
      problems.push(`${file}: Q${item.number} has unknown type "${item.type}"`);
    }
    if (!item.answer || !String(item.answer).trim()) {
      problems.push(`${file}: Q${item.number} has an empty answer`);
    }
    total += item.points;
  }
  if (Math.abs(total - 15) > 0.001) {
    problems.push(`${file}: total is ${total}, expected 15`);
  }

  const seen = new Set(key.map((k) => k.number));
  if (seen.size !== 15) problems.push(`${file}: duplicate question numbers`);

  rows.push({ subject, grade, doc, notes, key });
}

if (problems.length) {
  console.error("Refusing to generate SQL — invalid answer keys:");
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const out = [];
out.push("-- Gnahatum: diagnostic tests and answer keys");
out.push("--");
out.push("-- GENERATED by scripts/build-gnahatum-keys-sql.mjs — do not hand-edit.");
out.push("-- Idempotent: ON CONFLICT DO UPDATE on (subject_id, grade, test_type, year).");
out.push("--");
out.push("-- Answer keys are transcribed from the Հավելված 1 (Թեստի բանալի) section of");
out.push("-- each official test document linked from the subject guide. Where a source");
out.push("-- key contradicts itself or is incomplete, that is recorded in scoring_notes");
out.push("-- rather than silently corrected.");
out.push("");
out.push("-- Requires gnahatum_learning_layer.sql to have been applied first: the");
out.push("-- history tests reference subject ids that migration creates.");
out.push("");

for (const row of rows) {
  const answerKey = JSON.stringify(row.key);
  out.push(
    `INSERT INTO ararka.tests (subject_id, grade, test_type, year, total_points, answer_key, scoring_notes, source_file_id)`,
  );
  out.push(
    `VALUES (${sqlString(row.subject)}, ${row.grade}, 'diagnostic', '${YEAR}', 15.0, ${sqlString(answerKey)}::jsonb, ${sqlString(row.notes ?? null)}, ${sqlString(row.doc ?? null)})`,
  );
  out.push(`ON CONFLICT (subject_id, grade, test_type, year) DO UPDATE`);
  out.push(
    `  SET answer_key = EXCLUDED.answer_key, scoring_notes = EXCLUDED.scoring_notes, source_file_id = EXCLUDED.source_file_id, total_points = EXCLUDED.total_points;`,
  );
  out.push("");
}

out.push("-- Remove the two rows that correspond to nothing in the subject guide.");
out.push("-- `english` grade 1 and `armenian_lang` grade 2 were mis-seeded: English");
out.push("-- starts at grade 4 (§6) and Հայոց լեզու at grade 5 (§3); grade 1-2 material");
out.push("-- belongs to armenian_elementary / math_elementary. Guarded so a row that has");
out.push("-- already been scanned against is kept rather than silently destroyed.");
out.push("DELETE FROM ararka.tests t");
out.push(" WHERE t.test_type = 'diagnostic'");
out.push("   AND ((t.subject_id = 'english' AND t.grade = 1)");
out.push("     OR (t.subject_id = 'armenian_lang' AND t.grade = 2))");
out.push("   AND NOT EXISTS (SELECT 1 FROM ararka.scans s WHERE s.test_id = t.id);");
out.push("");

console.log(out.join("\n"));
console.error(`Generated ${rows.length} tests.`);
